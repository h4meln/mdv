"""Run with Python + Pillow after adding photos to data/gallery.js."""
from pathlib import Path
from PIL import Image
import base64
import io
import json
import re
root = Path(__file__).resolve().parents[1]
previews = {}
for src in re.findall(r"src:\s*'([^']+)'", (root / 'data/gallery.js').read_text(encoding='utf-8')):
    with Image.open(root / src) as photo:
        width, height = photo.size
        photo.thumbnail((24, 24))
        buffer = io.BytesIO()
        photo.convert('RGB').save(buffer, format='WEBP', quality=25)
        previews[src] = dict(w=width, h=height, preview='data:image/webp;base64,' + base64.b64encode(buffer.getvalue()).decode())
(root / 'data/gallery-previews.js').write_text('// Generated by scripts/build-gallery-previews.py\nexport const GALLERY_PREVIEWS = ' + json.dumps(previews, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'Generated {len(previews)} previews')
